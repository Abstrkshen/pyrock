//! Rust source emission. One Rust function per specialization; Python
//! semantics that differ from Rust operators go through `pyfast_runtime`.
//! Output is meant to be read: it keeps Python names and adds a doc line
//! per function pointing back to the source.
//!
//! Boundaries:
//! * Rust modules are included with `#[path] mod`, C modules are declared
//!   in an `extern "C"` block and compiled by the generated `build.rs`.
//! * CPython objects are `rt::py::Obj`; native values are boxed exactly
//!   where they meet one, and unboxed only through checked conversions.

mod class;
mod closure;
mod coll;
mod ext;

pub(crate) use closure::literal_obj as closure_literal_obj;

use pyfast_analysis::Plan;
use pyfast_infer::{CallClass, Program, Slot, Spec, SpecKey};
use pyfast_ir::*;
use std::fmt::Write;

pub struct Emitted {
    pub main_rs: String,
    /// `build.rs` contents when C modules must be compiled.
    pub build_rs: Option<String>,
    /// (rust function name, python span) pairs for the source map.
    pub source_map: Vec<(String, Span)>,
}

/// `py_paths`: directories prepended to the embedded interpreter's `sys.path`.
pub fn emit(prog: &Program, plan: &Plan, file_name: &str, py_paths: &[String]) -> Emitted {
    let m = prog.module;
    let mut out = String::new();
    let mut source_map = Vec::new();
    writeln!(out, "// Generated by pyfast {} from {file_name}. Do not edit.", env!("CARGO_PKG_VERSION")).unwrap();
    writeln!(out, "#![allow(dead_code, path_statements, non_camel_case_types, unused_mut, unused_variables, unused_assignments, unused_parens, unreachable_code, non_snake_case, non_upper_case_globals, unused_unsafe)]").unwrap();
    writeln!(out, "#![allow(clippy::all)]\n").unwrap();
    writeln!(out, "use pyfast_runtime as rt;").unwrap();
    writeln!(out, "use rt::PyResult;").unwrap();

    // Linked Rust and C modules (and handles to their structs).
    ext::emit_decls(m, &plan.externs_used, &mut out);

    // CPython import slots and once-flags for natively compiled modules.
    if !m.slots.is_empty() && plan.uses_python {
        out.push('\n');
        for (i, s) in m.slots.iter().enumerate() {
            writeln!(out, "static SLOT_{i}_{}: rt::py::Slot = rt::py::Slot::new({:?});", ident(&s.binding), s.binding).unwrap();
        }
    }
    // Module-level variables read by functions (or other modules).
    let mut first = true;
    for (u, name) in &m.globals {
        let Some(t) = prog.globals.get(&(*u, name.clone())).and_then(|s| s.known()) else { continue };
        if first {
            out.push('\n');
            first = false;
        }
        writeln!(out, "thread_local! {{ static {}: std::cell::RefCell<Option<{}>> = const {{ std::cell::RefCell::new(None) }}; }}", gname(*u, name), t.rust()).unwrap();
    }
    class::emit_classes(prog, plan, &mut out);
    class::emit_unions(prog, &mut out);
    closure::emit_boxers(prog, &mut out);
    for s in prog.specs.iter().filter(|s| plan.is_reachable(s.id)) {
        let f = &m.funcs[s.key.func];
        if f.is_module && f.unit != 0 {
            writeln!(out, "static INIT_{}: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);", m.units[f.unit].name).unwrap();
        }
    }

    let mut items: Vec<String> = Vec::new();
    for s in prog.specs.iter().skip(1).filter(|s| plan.is_reachable(s.id)) {
        out.push('\n');
        let f = &m.funcs[s.key.func];
        source_map.push((s.mangled.clone(), f.span));
        items.extend(FnEmitter::new(prog, plan, s).emit(&mut out));
    }
    let main = prog.main_spec();
    out.push('\n');
    source_map.push((main.mangled.clone(), Span::default()));
    items.extend(FnEmitter::new(prog, plan, main).emit(&mut out));
    for it in items {
        writeln!(out, "\n{it}").unwrap();
    }

    writeln!(out, "\nfn main() {{").unwrap();
    if plan.uses_python {
        let paths: Vec<String> = py_paths.iter().map(|p| format!("{p:?}")).collect();
        writeln!(out, "    rt::py::init({file_name:?}, &[{}]);", paths.join(", ")).unwrap();
    }
    // The program's exception classes, for `except` matching.
    let mut excs = Vec::new();
    for cd in &m.classes {
        let short = cd.name.rsplit('.').next().unwrap_or("").to_string();
        match &cd.base {
            Some(ClassBase::Exception(b)) => excs.push(format!("({short:?}, {b:?})")),
            Some(ClassBase::Native(b)) if m.exception_base(cd.id).is_some() => {
                let bs = m.class(*b).name.rsplit('.').next().unwrap_or("").to_string();
                excs.push(format!("({short:?}, {bs:?})"));
            }
            _ => {}
        }
    }
    if !excs.is_empty() {
        writeln!(out, "    rt::exc::register(&[{}]);", excs.join(", ")).unwrap();
    }
    writeln!(out, "    rt::run_main({file_name:?}, module_body)\n}}").unwrap();

    let c_mods: Vec<&ExternModule> = m.externs.iter().enumerate().filter(|(i, x)| x.lang == Lang::C && plan.externs_used.contains(i)).map(|(_, x)| x).collect();
    let build_rs = (!c_mods.is_empty()).then(|| {
        let mut b = String::from("// Generated by pyfast: compiles imported C modules.\nfn main() {\n");
        for x in c_mods {
            ext::build_lines(x, &mut b);
        }
        b.push_str("    #[cfg(unix)]\n    println!(\"cargo:rustc-link-lib=m\");\n}\n");
        b
    });
    Emitted { main_rs: out, build_rs, source_map }
}

/// Rust spelling of a Python local. Rust keywords become raw identifiers
/// (`type` -> `r#type`); names that cannot be raw (`_`, `self`, ...) and
/// names that could collide with generated temporaries (`__x`) get a `py_` prefix.
pub(crate) fn rid(name: &str) -> String {
    const RAW: &[&str] = &[
        "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for", "if",
        "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait",
        "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "gen", "macro",
        "override", "priv", "try", "typeof", "unsized", "virtual", "yield",
    ];
    match name {
        "_" | "self" | "Self" | "super" | "crate" => format!("py_{name}"),
        n if n.starts_with("__") => format!("py{n}"),
        n if RAW.contains(&n) => format!("r#{n}"),
        n => n.to_string(),
    }
}

/// Rust name of a global cell.
fn gname(unit: usize, name: &str) -> String {
    format!("G{unit}_{}", ident(name))
}

fn ident(s: &str) -> String {
    s.chars().map(|c| if c.is_alphanumeric() { c } else { '_' }).collect()
}

struct FnEmitter<'a, 'p> {
    prog: &'a Program<'p>,
    plan: &'a Plan,
    spec: &'a Spec,
    func: &'a Function,
    tmp: usize,
    /// Number of enclosing `try`/`with` closures.
    try_depth: usize,
    /// For each enclosing loop, the `try_depth` at which it was opened.
    loops: Vec<usize>,
    /// Rust names of the exceptions being handled (innermost last), for bare `raise`.
    handling: Vec<String>,
    /// Program-level items this function needs (C callback trampolines).
    cfn_items: Vec<String>,
}

/// Whether a block contains a statement compiled into a closure.
fn has_closure_stmt(stmts: &[Stmt]) -> bool {
    stmts.iter().any(|s| match &s.kind {
        StmtKind::Try { .. } | StmtKind::With { .. } => true,
        StmtKind::If { body, orelse, .. } => has_closure_stmt(body) || has_closure_stmt(orelse),
        StmtKind::While { body, .. } | StmtKind::ForRange { body, .. } | StmtKind::ForIter { body, .. } => has_closure_stmt(body),
        _ => false,
    })
}

/// The type a call to `s` produces: what its body returns, or a coroutine of
/// it for an `async def`.
pub(crate) fn call_ret(prog: &Program, s: &Spec) -> Ty {
    let r = ret_ty(s);
    if prog.module.funcs[s.key.func].is_generator {
        return Ty::gen(r);
    }
    if prog.module.funcs[s.key.func].is_async {
        Ty::coro(r)
    } else {
        r
    }
}

fn ret_ty(s: &Spec) -> Ty {
    match s.ret {
        Slot::Known(t) => t,
        Slot::Boxed(..) => Ty::Obj,
        _ => Ty::None,
    }
}

fn float_lit(v: f64) -> String {
    if v.is_nan() {
        "f64::NAN".into()
    } else if v.is_infinite() {
        if v > 0.0 { "f64::INFINITY".into() } else { "f64::NEG_INFINITY".into() }
    } else {
        let s = format!("{v:?}");
        let s = if s.contains(['.', 'e']) { s } else { format!("{s}.0") };
        if v.is_sign_negative() { format!("({s}_f64)") } else { format!("{s}_f64") }
    }
}

/// Coerce a numeric value to i64 (bool -> int, object -> checked unbox).
fn as_int(code: &str, t: Ty) -> String {
    match t {
        Ty::Bool => format!("({code} as i64)"),
        Ty::Obj => format!("rt::py::to_i64(&{})?", borrow(code)),
        _ => code.to_string(),
    }
}

/// Coerce a numeric value to f64 (int/bool -> float, correctly rounded).
fn as_float(code: &str, t: Ty) -> String {
    match t {
        Ty::Bool => format!("({code} as i64 as f64)"),
        Ty::Int => format!("({code} as f64)"),
        Ty::Obj => format!("rt::py::to_f64(&{})?", borrow(code)),
        _ => code.to_string(),
    }
}

/// Wrap a native value as a Python object.
pub(crate) fn boxed(code: &str, t: Ty) -> String {
    match t {
        Ty::Int => format!("rt::py::int({code})"),
        Ty::Float => format!("rt::py::float({code})"),
        Ty::Bool => format!("rt::py::bool_({code})"),
        Ty::Str => format!("rt::py::str_(&{})", borrow(code)),
        Ty::None if code == "()" => "rt::py::none()".into(),
        Ty::None => format!("{{ {code}; rt::py::none() }}"),
        Ty::Obj => code.to_string(),
        Ty::C(_) if t.as_closure().is_some() => format!("box_{}({code})", t.mangle()),
        Ty::C(_) if t.union_members().is_some_and(|ms| ms.iter().all(|m| m.as_closure().is_some())) => {
            let arms: Vec<String> = t.union_members().unwrap().iter().map(|m| format!("{}::{}(__f) => box_{}(__f)", t.rust(), m.variant_name(), m.mangle())).collect();
            format!("match {code} {{ {} }}", arms.join(", "))
        }
        Ty::C(_) => format!("rt::py::to_py(&{})?", borrow(code)),
    }
}

/// Convert a value of type `from` for a slot of type `to`. Inference only
/// joins types by boxing, so the only conversion needed is native -> object.
fn coerce(code: String, from: Ty, to: Ty) -> String {
    if from == to {
        return code;
    }
    let comp = |t: Ty| t.as_comp().is_some_and(|c| !matches!(c, Comp::Opt(_)));
    if (comp(from) && comp(to)) || from.is_never() || (to.as_opt().is_some_and(|x| x.as_comp().is_some()) && from != Ty::None) {
        return coll::convert(&code, from, to);
    }
    coerce_basic(code, from, to)
}

/// Scalar / Optional / boxing coercions (no container conversion).
fn coerce_basic(code: String, from: Ty, to: Ty) -> String {
    if from == to {
        return code;
    }
    if to.as_opt().is_some() {
        return match from {
            Ty::None if code == "()" => "None".into(),
            Ty::None => format!("{{ {code}; None }}"),
            t if t.as_opt().is_some() => code,
            _ => format!("Some({code})"),
        };
    }
    if to != Ty::Obj {
        code
    } else {
        boxed(&code, from)
    }
}

/// Unwrap a `T | None` operand where CPython needs a `T` (TypeError on None).
fn unopt(code: String, t: Ty, msg: &str) -> (String, Ty) {
    match t.as_opt() {
        Some(inner) => (format!("rt::unopt({code}, {msg:?})?"), inner),
        None => (code, t),
    }
}

/// CPython's name for the type of a value of static type `t`.
fn tname(t: Ty) -> &'static str {
    match t {
        Ty::None => "NoneType",
        t => t.as_opt().unwrap_or(t).py_name(),
    }
}

/// An operand that is only borrowed does not need its `.clone()`.
fn borrow(code: &str) -> &str {
    match code.strip_suffix(".clone()") {
        Some(id) if id.chars().all(|c| c.is_alphanumeric() || c == '_' || c == '#') => id,
        _ => code,
    }
}

/// Drop one redundant pair of outer parentheses (for `if`/`while` heads).
fn unparen(code: &str) -> &str {
    let Some(inner) = code.strip_prefix('(').and_then(|c| c.strip_suffix(')')) else { return code };
    let mut depth = 0i32;
    for ch in inner.chars() {
        match ch {
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth < 0 {
                    return code;
                }
            }
            _ => {}
        }
    }
    if depth == 0 { inner } else { code }
}

fn truthy(code: &str, t: Ty) -> String {
    match t {
        Ty::Bool => code.to_string(),
        Ty::Int => format!("({code} != 0)"),
        Ty::Float => format!("({code} != 0.0)"),
        Ty::Str => format!("!{code}.is_empty()"),
        Ty::None => format!("{{ {code}; false }}"),
        Ty::Obj => format!("rt::py::truthy(&{})?", borrow(code)),
        Ty::C(_) => format!("rt::truthy(&{})", borrow(code)),
    }
}

fn to_str(code: &str, t: Ty) -> String {
    match t {
        Ty::Int => format!("rt::conv::str_int({code})"),
        Ty::Float => format!("rt::conv::str_float({code})"),
        Ty::Bool => format!("rt::conv::str_bool({code})"),
        Ty::Str => code.to_string(),
        Ty::None => format!("{{ {code}; rt::conv::str_none() }}"),
        Ty::Obj => format!("rt::py::str_of(&{})?", borrow(code)),
        Ty::C(_) => format!("rt::conv::str_of(&{})", borrow(code)),
    }
}

/// Python operator-module name for a binary operator.
fn py_op(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "add",
        BinOp::Sub => "sub",
        BinOp::Mul => "mul",
        BinOp::Div => "truediv",
        BinOp::FloorDiv => "floordiv",
        BinOp::Mod => "mod",
        BinOp::Pow => "pow",
        BinOp::BitAnd => "and_",
        BinOp::BitOr => "or_",
        BinOp::BitXor => "xor",
        BinOp::LShift => "lshift",
        BinOp::RShift => "rshift",
    }
}

/// In-place variant (`x += y` on a list must mutate it, preserving aliasing).
fn py_iop(op: BinOp) -> String {
    match op {
        BinOp::BitAnd => "iand".into(),
        BinOp::BitOr => "ior".into(),
        BinOp::BitXor => "ixor".into(),
        o => format!("i{}", py_op(o)),
    }
}

impl<'a, 'p> FnEmitter<'a, 'p> {
    fn new(prog: &'a Program<'p>, plan: &'a Plan, spec: &'a Spec) -> Self {
        let func = &prog.module.funcs[spec.key.func];
        FnEmitter { prog, plan, spec, func, tmp: 0, try_depth: 0, loops: vec![], handling: vec![], cfn_items: vec![] }
    }

    fn fresh(&mut self) -> String {
        self.tmp += 1;
        format!("__t{}", self.tmp)
    }

    fn ty(&self, e: &Expr) -> Ty {
        match self.prog.type_of(self.spec, e) {
            Some(t) => t,
            None => panic!(
                "codegen on an ill-typed expression at {}:{} in {}; inference should have rejected it",
                e.span.line,
                e.span.col,
                pyfast_infer::spec_label(self.prog, self.spec)
            ),
        }
    }

    fn local_ty(&self, name: &str) -> Option<Ty> {
        self.spec.locals.get(name).and_then(|s| s.known())
    }

    fn file(&self) -> &str {
        &self.prog.module.units[self.func.unit].path
    }

    fn emit(mut self, out: &mut String) -> Vec<String> {
        let s = self.spec;
        let f = self.func;
        let ret = self.body_ret();
        let file = self.file().rsplit('/').next().unwrap_or("").to_string();
        if f.is_module {
            if f.unit == 0 {
                writeln!(out, "/// Module body of {file}.").unwrap();
                writeln!(out, "fn module_body() -> PyResult<()> {{").unwrap();
            } else {
                let name = &self.prog.module.units[f.unit].name;
                writeln!(out, "/// Module body of {file} (runs once, at its first import).").unwrap();
                writeln!(out, "fn {}() -> PyResult<()> {{", s.mangled).unwrap();
                writeln!(out, "    if !rt::first_import(&INIT_{name}) {{\n        return Ok(());\n    }}").unwrap();
            }
        } else {
            let off = pyfast_infer::spec::env_offset(f);
            let args = &s.key.args[off..];
            let params: Vec<String> = f.params.iter().zip(args).map(|(p, t)| format!("{p}: {t}")).collect();
            writeln!(out, "/// `{}({}) -> {ret}`, specialized from {file}:{}", f.name, params.join(", "), f.span.line).unwrap();
            // A parameter whose local type is wider than its argument (e.g. a
            // `None` default later assigned an int) is rebound with a coercion;
            // a parameter captured by a nested function moves into a cell.
            let widened = |p: &String, t: &Ty| self.local_ty(p).is_some_and(|lt| lt != *t) || f.cells.contains(p);
            let mut params: Vec<String> = if off == 1 { vec![format!("__env: {}", s.key.args[0].rust())] } else { vec![] };
            params.extend(
                f.params
                    .iter()
                    .zip(args)
                    .map(|(p, t)| if widened(p, t) { format!("__arg_{}: {}", rid(p).trim_start_matches("r#"), t.rust()) } else { format!("mut {}: {}", rid(p), t.rust()) }),
            );
            // `async def` / generator: the body is `<name>__body`; `<name>`
            // makes the coroutine / generator object around it.
            if f.is_async || f.is_generator {
                let (kind, item) = if f.is_generator { ("rt::gen::Gen", ret_ty(s)) } else { ("rt::aio::Coro", ret) };
                let names: Vec<String> = params.iter().map(|p| p.trim_start_matches("mut ").split(':').next().unwrap().to_string()).collect();
                let wparams: Vec<String> = params.iter().map(|p| p.trim_start_matches("mut ").to_string()).collect();
                writeln!(
                    out,
                    "fn {m}({}) -> PyResult<{kind}<{r}>> {{\n    Ok({kind}::new({:?}, move || {m}__body({})))\n}}\n",
                    wparams.join(", "),
                    f.name.rsplit('.').next().unwrap_or(&f.name),
                    names.join(", "),
                    m = s.mangled,
                    r = item.rust()
                )
                .unwrap();
            }
            let fname = if f.is_async || f.is_generator { format!("{}__body", s.mangled) } else { s.mangled.clone() };
            writeln!(out, "fn {}({}) -> PyResult<{}> {{", fname, params.join(", "), ret.rust()).unwrap();
            for (p, t) in f.params.iter().zip(args) {
                if widened(p, t) {
                    let lt = self.local_ty(p).unwrap_or(*t);
                    let arg = format!("__arg_{}", rid(p).trim_start_matches("r#"));
                    if f.cells.contains(p) {
                        writeln!(out, "    let {}: rt::Cell<{}> = rt::cell();\n    rt::cset(&{}, {});", rid(p), lt.rust(), rid(p), coerce(arg, *t, lt)).unwrap();
                    } else {
                        writeln!(out, "    let mut {}: {} = {};", rid(p), lt.rust(), coerce(arg, *t, lt)).unwrap();
                    }
                }
            }
            if off == 1 {
                if let Some((_, caps)) = s.key.args[0].as_closure() {
                    for (i, (n, t)) in f.captures.iter().zip(caps).enumerate() {
                        writeln!(out, "    let {}: rt::Cell<{}> = __env.0.{i}.clone();", rid(n), t.rust()).unwrap();
                    }
                }
            }
            if self.plan.is_recursive(s.id) {
                writeln!(out, "    let _frame = rt::enter()?; // recursive: enforce the recursion limit").unwrap();
            }
        }
        let captured = has_closure_stmt(&f.body);
        for name in &f.locals {
            if f.params.contains(name) {
                continue;
            }
            let Some(t) = self.local_ty(name) else { continue };
            if f.cells.contains(name) {
                writeln!(out, "    let {}: rt::Cell<{}> = rt::cell();", rid(name), t.rust()).unwrap();
            } else if s.maybe_unbound.contains(name) {
                writeln!(out, "    let mut {}: Option<{}> = None;", rid(name), t.rust()).unwrap();
            } else if captured {
                // Closures (try/with bodies) cannot capture uninitialised locals.
                writeln!(out, "    let mut {}: {} = {};", rid(name), t.rust(), t.rust_placeholder()).unwrap();
            } else {
                writeln!(out, "    let mut {}: {};", rid(name), t.rust()).unwrap();
            }
        }
        let mut body = String::new();
        self.block(&f.body, 1, &mut body);
        out.push_str(&body);
        if s.falls_through || f.is_module {
            if ret == Ty::Obj {
                writeln!(out, "    Ok(rt::py::none())").unwrap();
            } else if ret.as_opt().is_some() {
                writeln!(out, "    Ok(None)").unwrap();
            } else {
                writeln!(out, "    Ok(())").unwrap();
            }
        } else if captured {
            // Inference proved control never reaches the end; a trailing
            // `match` on a try result still needs a diverging tail.
            writeln!(out, "    unreachable!(\"control cannot reach the end of {}\")", f.name).unwrap();
        }
        writeln!(out, "}}").unwrap();
        self.cfn_items
    }

    fn block(&mut self, stmts: &[Stmt], depth: usize, out: &mut String) {
        for s in stmts {
            self.stmt(s, depth, out);
            // What follows is dead (inference did not type it).
            if !pyfast_infer::spec::falls_through(&self.spec.locals, s) {
                break;
            }
        }
    }

    fn assign(&mut self, target: &str, code: String, from: Ty, depth: usize, out: &mut String) {
        let ind = "    ".repeat(depth);
        let to = self.local_ty(target).unwrap_or(from);
        let code = coerce(code, from, to);
        let var = rid(target);
        if self.is_cell(target) {
            writeln!(out, "{ind}rt::cset(&{var}, {code});").unwrap();
            return;
        }
        if self.spec.maybe_unbound.contains(target) {
            writeln!(out, "{ind}{var} = Some({code});").unwrap();
        } else {
            writeln!(out, "{ind}{var} = {code};").unwrap();
        }
    }

    fn obj(&mut self, e: &Expr) -> String {
        let (c, t) = self.expr(e);
        boxed(&c, t)
    }

    fn stmt(&mut self, s: &Stmt, depth: usize, out: &mut String) {
        let ind = "    ".repeat(depth);
        match &s.kind {
            StmtKind::Assign { target, value } => {
                match self.local_ty(target) {
                    Some(to) => {
                        let code = self.expr_as(value, to);
                        self.assign(target, code, to, depth, out);
                    }
                    None => {
                        let (code, t) = self.expr(value);
                        self.assign(target, code, t, depth, out);
                    }
                }
            }
            StmtKind::AugAssign { target, op, value } => {
                let cur = Expr { kind: ExprKind::Local(target.clone()), span: s.span };
                if self.local_ty(target) == Some(Ty::Obj) {
                    // In-place protocol: `a += [x]` mutates the list `a` refers to.
                    let (c, _) = self.expr(&cur);
                    let v = self.obj(value);
                    let code = format!("rt::py::binop({:?}, {c}, {v})?", py_iop(*op));
                    self.assign(target, code, Ty::Obj, depth, out);
                    return;
                }
                if let Some(tt) = self.local_ty(target).filter(|t| t.is_mutable()) {
                    // In-place: `xs += ys` / `s |= t` mutate the object (aliases see it).
                    let (c, _) = self.expr(&cur);
                    let (v, vt) = self.expr(value);
                    let code = match (tt.as_comp(), op) {
                        (Some(Comp::List(e)), BinOp::Add) => {
                            let ve = pyfast_infer::native::iter_elem(vt).unwrap_or(e);
                            let items = coll::iter_vec(&v, vt);
                            let items = if ve == e { items } else { format!("{items}.into_iter().map(|__e| {}).collect()", coll::convert("__e", ve, e)) };
                            format!("{{ let __v = {items}; {c}.extend(__v); }}")
                        }
                        (Some(Comp::List(_)), BinOp::Mul) => format!("{{ let __n = {}; let __v = {c}.repeat(__n).to_vec(); {c}.clear(); {c}.extend(__v); }}", as_int(&v, vt)),
                        (Some(Comp::Set(_)), BinOp::BitOr) => format!("{c}.update({});", coll::iter_vec(&v, vt)),
                        (Some(Comp::Set(_)), _) => {
                            let m = match op {
                                BinOp::BitAnd => "intersection",
                                BinOp::Sub => "difference",
                                _ => "symmetric_difference",
                            };
                            format!("{{ let __n = {c}.{m}(&{}); {c}.clear(); {c}.update(__n.to_vec()); }}", coll::convert(&v, vt, tt))
                        }
                        (Some(Comp::Dict(..)), _) => format!("{c}.update(&{});", coll::convert(&v, vt, tt)),
                        _ => unreachable!("in-place operator on {tt}"),
                    };
                    writeln!(out, "{ind}{code}").unwrap();
                    return;
                }
                let e = Expr { kind: ExprKind::BinOp { op: *op, left: Box::new(cur), right: Box::new(value.clone()) }, span: s.span };
                let (code, t) = self.expr(&e);
                self.assign(target, code, t, depth, out);
            }
            StmtKind::Expr(e) => {
                if matches!(e.kind, ExprKind::Int(_) | ExprKind::Float(_) | ExprKind::Str(_) | ExprKind::Bool(_) | ExprKind::NoneLit) {
                    return; // docstrings and bare literals have no effect
                }
                let (code, t) = self.expr(e);
                if t == Ty::None {
                    writeln!(out, "{ind}{code};").unwrap();
                } else {
                    writeln!(out, "{ind}let _ = {code};").unwrap();
                }
            }
            StmtKind::Return(v) => {
                let ret = self.body_ret();
                let (code, t) = match v {
                    Some(e) => (self.expr_as(e, ret), ret),
                    None => ("()".into(), Ty::None),
                };
                let code = coerce(code, t, ret);
                if self.try_depth > 0 {
                    writeln!(out, "{ind}return Ok(rt::Flow::Return({code}));").unwrap();
                    return;
                }
                // `return Ok(f(x)?)` is just `return f(x)`.
                match code.strip_suffix('?') {
                    Some(inner) if !code.starts_with('{') && !inner.contains("?") => writeln!(out, "{ind}return {inner};").unwrap(),
                    _ => writeln!(out, "{ind}return Ok({code});").unwrap(),
                }
            }
            StmtKind::If { test, body, orelse } => {
                if matches!(test.kind, ExprKind::Bool(true)) && orelse.is_empty() {
                    // Synthetic block (e.g. chained assignment, multi-import).
                    self.block(body, depth, out);
                    return;
                }
                // Decided by this specialization's types (`x is None` with x: None).
                match self.prog.static_truth(self.spec, test) {
                    Some(true) if !matches!(test.kind, ExprKind::Bool(_)) => return self.block(body, depth, out),
                    Some(false) if !matches!(test.kind, ExprKind::Bool(_)) => return self.block(orelse, depth, out),
                    _ => {}
                }
                let (c, t) = self.expr(test);
                writeln!(out, "{ind}if {} {{", unparen(&truthy(&c, t))).unwrap();
                self.block(body, depth + 1, out);
                let mut orelse = orelse.as_slice();
                loop {
                    if orelse.is_empty() {
                        writeln!(out, "{ind}}}").unwrap();
                        break;
                    }
                    if let [Stmt { kind: StmtKind::If { test, body, orelse: next }, .. }] = orelse {
                        let decided = self.prog.static_truth(self.spec, test).is_some() && !matches!(test.kind, ExprKind::Bool(_));
                        if !decided && (!matches!(test.kind, ExprKind::Bool(true)) || !next.is_empty()) {
                            let (c, t) = self.expr(test);
                            writeln!(out, "{ind}}} else if {} {{", unparen(&truthy(&c, t))).unwrap();
                            self.block(body, depth + 1, out);
                            orelse = next.as_slice();
                            continue;
                        }
                    }
                    writeln!(out, "{ind}}} else {{").unwrap();
                    self.block(orelse, depth + 1, out);
                    writeln!(out, "{ind}}}").unwrap();
                    break;
                }
            }
            StmtKind::While { test, body } => {
                if self.prog.static_truth(self.spec, test) == Some(false) && !matches!(test.kind, ExprKind::Bool(_)) {
                    return;
                }
                if matches!(test.kind, ExprKind::Bool(true)) {
                    writeln!(out, "{ind}loop {{").unwrap();
                } else {
                    let (c, t) = self.expr(test);
                    writeln!(out, "{ind}while {} {{", unparen(&truthy(&c, t))).unwrap();
                }
                self.loop_body(body, depth + 1, out);
                writeln!(out, "{ind}}}").unwrap();
            }
            StmtKind::ForRange { var, start, stop, step, body } => {
                let v = format!("__{}", rid(var).trim_start_matches("r#"));
                let int = |me: &mut Self, e: &Expr| {
                    let (c, t) = me.expr(e);
                    let (c, t) = unopt(c, t, "'NoneType' object cannot be interpreted as an integer");
                    as_int(&c, t)
                };
                let iter = match (start, step) {
                    (None, None) => format!("0..{}", int(self, stop)),
                    (Some(a), None) => {
                        let a = int(self, a);
                        let b = int(self, stop);
                        if a.contains('?') || b.contains('?') {
                            // keep Python's left-to-right evaluation explicit
                            let (ta, tb) = (self.fresh(), self.fresh());
                            writeln!(out, "{ind}let {ta} = {a};\n{ind}let {tb} = {b};").unwrap();
                            format!("{ta}..{tb}")
                        } else {
                            format!("{a}..{b}")
                        }
                    }
                    (a, Some(st)) => {
                        let a = a.as_ref().map(|a| int(self, a)).unwrap_or_else(|| "0".into());
                        let b = int(self, stop);
                        let c = int(self, st);
                        format!("rt::int::range({a}, {b}, {c})?")
                    }
                };
                writeln!(out, "{ind}for {v} in {iter} {{").unwrap();
                self.assign(var, v.clone(), Ty::Int, depth + 1, out);
                self.loop_body(body, depth + 1, out);
                writeln!(out, "{ind}}}").unwrap();
            }
            StmtKind::ForIter { var, iter, body, is_async: false } if pyfast_infer::spec::class_like(self.ty(iter)) => {
                let it = self.expr(iter);
                let call = self.dunder(it.clone(), "__iter__", vec![]).unwrap();
                let c = it.1.class_id().unwrap();
                let m = self.prog.module.find_method(c, "__iter__").unwrap();
                let rt = self.prog.spec(&SpecKey { func: m.func, args: vec![it.1] }).and_then(|s| match s.ret {
                    Slot::Known(t) => Some(t),
                    _ => None,
                }).unwrap_or(Ty::Obj);
                let n = self.fresh();
                writeln!(out, "{ind}let __it{n} = {call};").unwrap();
                let elem = pyfast_infer::native::iter_elem(rt).unwrap_or(Ty::Obj);
                writeln!(out, "{ind}for __v in {} {{", coll::iter_vec(&format!("__it{n}"), rt)).unwrap();
                self.assign(var, "__v".into(), elem, depth + 1, out);
                self.loop_body(body, depth + 1, out);
                writeln!(out, "{ind}}}").unwrap();
            }
            StmtKind::ForIter { var, iter, body, is_async: false } if self.ty(iter) != Ty::Obj => {
                let it = self.ty(iter);
                let (head, v) = self.for_native(iter, it, &ind, out);
                let elem = pyfast_infer::native::iter_elem(it).unwrap();
                writeln!(out, "{ind}{head} {{").unwrap();
                self.assign(var, v, elem, depth + 1, out);
                self.loop_body(body, depth + 1, out);
                writeln!(out, "{ind}}}").unwrap();
            }
            StmtKind::ForIter { var, iter, body, is_async } => {
                let it = self.fresh();
                let src = self.obj(iter);
                let make = if *is_async { "rt::aio::aiter" } else { "rt::py::iter" };
                writeln!(out, "{ind}let mut {it} = {make}(&{})?;", borrow(&src)).unwrap();
                writeln!(out, "{ind}while let Some(__v) = {it}.next()? {{").unwrap();
                self.assign(var, "__v".into(), Ty::Obj, depth + 1, out);
                self.loop_body(body, depth + 1, out);
                writeln!(out, "{ind}}}").unwrap();
            }
            StmtKind::SetItem { obj, index, value } if pyfast_infer::spec::class_like(self.ty(obj)) => {
                let v = self.expr(value);
                let o = self.expr(obj);
                let i = self.expr(index);
                let call = self.dunder(o, "__setitem__", vec![i, v]).unwrap();
                writeln!(out, "{ind}let _ = {call};").unwrap();
            }
            StmtKind::SetAttr { obj, name, value } if self.ty(obj).as_ext_struct().is_some() => {
                let code = self.ext_set_field(obj, name, value, &ind);
                writeln!(out, "{code}").unwrap();
            }
            StmtKind::SetAttr { obj, name, value } if pyfast_infer::spec::class_like(self.ty(obj)) => {
                let code = self.set_attr(obj, name, value, &ind);
                writeln!(out, "{code}").unwrap();
            }
            StmtKind::SetItem { obj, index, value } if self.ty(obj) != Ty::Obj => {
                let code = self.set_item(obj, index, value, &ind);
                writeln!(out, "{code}").unwrap();
            }
            StmtKind::SetItem { obj, index, value } => {
                // Python evaluates the right-hand side first.
                let v = self.obj(value);
                let o = self.obj(obj);
                let i = self.obj(index);
                writeln!(out, "{ind}{{\n{ind}    let __v = {v};\n{ind}    rt::py::setitem(&{}, {i}, __v)?;\n{ind}}}", borrow(&o)).unwrap();
            }
            StmtKind::SetAttr { obj, name, value } => {
                let v = self.obj(value);
                let o = self.obj(obj);
                writeln!(out, "{ind}{{\n{ind}    let __v = {v};\n{ind}    rt::py::setattr(&{}, {name:?}, __v)?;\n{ind}}}", borrow(&o)).unwrap();
            }
            StmtKind::Import(ImportAction::Py(i)) => {
                let slot = &self.prog.module.slots[*i];
                let name = format!("SLOT_{i}_{}", ident(&slot.binding));
                match &slot.kind {
                    SlotKind::Import { module, bind_top } => writeln!(out, "{ind}{name}.import({module:?}, {bind_top})?;").unwrap(),
                    SlotKind::From { module, attr } => writeln!(out, "{ind}{name}.import_from({module:?}, {attr:?})?;").unwrap(),
                }
            }
            StmtKind::Import(ImportAction::Unit(fid)) => {
                let key = SpecKey { func: *fid, args: vec![] };
                if let Some(sp) = self.prog.spec(&key) {
                    writeln!(out, "{ind}{}()?;", sp.mangled).unwrap();
                }
            }
            StmtKind::AssignGlobal { unit, name, value } => {
                let gt = self.prog.globals.get(&(*unit, name.clone())).and_then(|s| s.known()).unwrap_or_else(|| self.ty(value));
                let code = self.expr_as(value, gt);
                writeln!(out, "{ind}rt::gset(&{}, {code});", gname(*unit, name)).unwrap();
            }
            StmtKind::Del(target) => match &target.kind {
                ExprKind::Subscript { obj, index } => {
                    let code = self.del_item(obj, index);
                    writeln!(out, "{ind}{code}").unwrap();
                }
                ExprKind::GetAttr { obj, name } => {
                    let o = self.obj(obj);
                    writeln!(out, "{ind}rt::py::delattr(&{}, {name:?})?;", borrow(&o)).unwrap();
                }
                _ => unreachable!(),
            },
            StmtKind::Break => writeln!(out, "{ind}{}", self.jump("break", "Break")).unwrap(),
            StmtKind::Continue => writeln!(out, "{ind}{}", self.jump("continue", "Continue")).unwrap(),
            StmtKind::Pass => {}
            StmtKind::Raise(e) => {
                let err = match e {
                    None => match self.handling.last() {
                        Some(v) => format!("{v}.clone()"),
                        None => "rt::exc::no_active()".into(),
                    },
                    Some(e) => {
                        let (c, t) = self.expr(e);
                        if t == Ty::Obj {
                            format!("rt::py::raise(&{})", borrow(&c))
                        } else if t.class_id().is_some() {
                            format!("{c}.into_exc()")
                        } else {
                            c
                        }
                    }
                };
                writeln!(out, "{ind}return Err({err});").unwrap();
            }
            StmtKind::Try { body, handlers, orelse, finalbody } => self.try_stmt(body, handlers, orelse, finalbody, depth, out),
            StmtKind::With { ctx, var, body, is_async } => {
                let n = self.fresh();
                let cm = self.obj(ctx);
                let (enter, exit) = if *is_async { ("rt::aio::aenter", "rt::aio::aexit") } else { ("rt::py::enter", "rt::py::exit") };
                writeln!(out, "{ind}let __cm{n} = {cm};").unwrap();
                writeln!(out, "{ind}let __v{n} = {enter}(&__cm{n})?;").unwrap();
                if let Some(v) = var {
                    self.assign(v, format!("__v{n}"), Ty::Obj, depth, out);
                }
                let r = format!("__r{n}");
                self.closure(&r, body, depth, out);
                writeln!(out, "{ind}let {r} = match {r} {{").unwrap();
                writeln!(out, "{ind}    Err(e) => if {exit}(&__cm{n}, Some(&e))? {{ Ok(rt::Flow::Normal) }} else {{ Err(e) }},").unwrap();
                writeln!(out, "{ind}    ok => {{ {exit}(&__cm{n}, None)?; ok }}").unwrap();
                writeln!(out, "{ind}}};").unwrap();
                self.propagate(&r, depth, out);
            }
        }
    }

    fn loop_body(&mut self, body: &[Stmt], depth: usize, out: &mut String) {
        self.loops.push(self.try_depth);
        self.block(body, depth, out);
        self.loops.pop();
    }

    /// `break`/`continue`: a plain jump when the loop is inside the current
    /// closure, otherwise a `Flow` value re-issued after the `try`.
    fn jump(&self, kw: &str, flow: &str) -> String {
        if self.loops.last() == Some(&self.try_depth) {
            format!("{kw};")
        } else {
            format!("return Ok(rt::Flow::{flow});")
        }
    }

    fn flow_ty(&self) -> String {
        format!("PyResult<rt::Flow<{}>>", self.body_ret().rust())
    }

    /// What the emitted body returns: the function's return type, or `()`
    /// for a generator body (its slot type is what it yields).
    fn body_ret(&self) -> Ty {
        if self.func.is_generator {
            Ty::None
        } else {
            ret_ty(self.spec)
        }
    }

    /// `let r = (|| -> PyResult<Flow<R>> { body; Ok(Flow::Normal) })();`
    fn closure(&mut self, r: &str, body: &[Stmt], depth: usize, out: &mut String) {
        let ind = "    ".repeat(depth);
        let ft = self.flow_ty();
        writeln!(out, "{ind}let {r}: {ft} = (|| -> {ft} {{").unwrap();
        self.try_depth += 1;
        self.block(body, depth + 1, out);
        self.try_depth -= 1;
        writeln!(out, "{ind}    Ok(rt::Flow::Normal)\n{ind}}})();").unwrap();
    }

    /// Re-issue how a closure body ended, in the current context.
    fn propagate(&mut self, r: &str, depth: usize, out: &mut String) {
        let ind = "    ".repeat(depth);
        let ret = if self.try_depth > 0 { "return Ok(rt::Flow::Return(v))".to_string() } else { "return Ok(v)".to_string() };
        writeln!(out, "{ind}match {r} {{").unwrap();
        writeln!(out, "{ind}    Ok(rt::Flow::Normal) => {{}}").unwrap();
        writeln!(out, "{ind}    Ok(rt::Flow::Return(v)) => {ret},").unwrap();
        if self.loops.is_empty() {
            writeln!(out, "{ind}    Ok(_) => unreachable!(),").unwrap();
        } else {
            writeln!(out, "{ind}    Ok(rt::Flow::Break) => {{ {} }}", self.jump("break", "Break")).unwrap();
            writeln!(out, "{ind}    Ok(rt::Flow::Continue) => {{ {} }}", self.jump("continue", "Continue")).unwrap();
        }
        writeln!(out, "{ind}    Err(e) => return Err(e),").unwrap();
        writeln!(out, "{ind}}}").unwrap();
    }

    fn try_stmt(&mut self, body: &[Stmt], handlers: &[Handler], orelse: &[Stmt], finalbody: &[Stmt], depth: usize, out: &mut String) {
        let ind = "    ".repeat(depth);
        let n = self.fresh();
        let r = format!("__r{n}");
        let e = format!("__e{n}");
        self.closure(&r, body, depth, out);
        if !handlers.is_empty() || !orelse.is_empty() {
            writeln!(out, "{ind}let {r} = match {r} {{").unwrap();
            if !orelse.is_empty() {
                let tmp = format!("{r}_else");
                writeln!(out, "{ind}    Ok(rt::Flow::Normal) => {{").unwrap();
                self.closure(&tmp, orelse, depth + 2, out);
                writeln!(out, "{ind}        {tmp}\n{ind}    }}").unwrap();
            }
            for h in handlers {
                let mut conds = Vec::new();
                for t in &h.types {
                    conds.push(match t {
                        ExcType::Builtin(k) => format!("rt::exc::matches(&{e}, {k:?})"),
                        ExcType::Native(c) => {
                            let short = self.prog.module.class(*c).name.rsplit('.').next().unwrap_or("").to_string();
                            format!("rt::exc::matches(&{e}, {short:?})")
                        }
                        ExcType::Obj(x) => {
                            let o = self.obj(x);
                            format!("rt::py::exc_matches(&{e}, &{})?", borrow(&o))
                        }
                    });
                }
                let guard = if conds.is_empty() { String::new() } else { format!(" if {}", conds.join(" || ")) };
                writeln!(out, "{ind}    Err({e}){guard} => {{").unwrap();
                let tmp = format!("{r}_h");
                let ft = self.flow_ty();
                writeln!(out, "{ind}        let {tmp}: {ft} = (|| -> {ft} {{").unwrap();
                self.try_depth += 1;
                if let Some(name) = &h.name {
                    match h.types.as_slice() {
                        [ExcType::Native(c)] => {
                            let r = self.prog.module.class(*c).rust.clone();
                            let t = Ty::class(*c, &r);
                            let code = format!("match rt::exc::downcast::<{r}>(&{e}) {{ Some(__x) => __x, None => {{ let __x = {r}::new(); __x.0.borrow_mut().exc_msg = Some(rt::Str::from({e}.msg.as_str())); __x }} }}");
                            self.assign(name, code, t, depth + 3, out);
                        }
                        _ => self.assign(name, format!("{e}.clone()"), Ty::exc(), depth + 3, out),
                    }
                }
                self.handling.push(e.clone());
                self.block(&h.body, depth + 3, out);
                self.handling.pop();
                self.try_depth -= 1;
                writeln!(out, "{ind}            Ok(rt::Flow::Normal)\n{ind}        }})();").unwrap();
                writeln!(out, "{ind}        {tmp}\n{ind}    }}").unwrap();
            }
            writeln!(out, "{ind}    other => other,\n{ind}}};").unwrap();
        }
        self.block(finalbody, depth, out);
        self.propagate(&r, depth, out);
    }

    /// Returns Rust code for the expression (already unwrapped from
    /// `PyResult`) together with its type.
    fn expr(&mut self, e: &Expr) -> (String, Ty) {
        let t = self.ty(e);
        // A value of type Never cannot exist: evaluate operands, then diverge.
        if t.is_never() && matches!(e.kind, ExprKind::BinOp { .. } | ExprKind::Unary { .. }) {
            let parts: Vec<String> = match &e.kind {
                ExprKind::BinOp { left, right, .. } => vec![self.expr(left).0, self.expr(right).0],
                ExprKind::Unary { operand, .. } => vec![self.expr(operand).0],
                _ => vec![],
            };
            let lets: String = parts.iter().map(|p| format!("let _ = {p}; ")).collect();
            return (format!("{{ {lets}unreachable!() }}"), t);
        }
        let is_class = pyfast_infer::spec::class_like;
        let code = match &e.kind {
            ExprKind::New { class, args, kwargs } => self.new_instance(e, *class, args, kwargs),
            ExprKind::ClassRef(_) => "()".into(),
            ExprKind::MakeClosure { captures, defaults, .. } => self.make_closure(captures, defaults),
            ExprKind::EnvDefault(_) => unreachable!("closure default outside a call"),
            ExprKind::EnvRead { value, index } => {
                let (v, _) = self.expr(value);
                format!("rt::cget(&({v}).0.{index}, \"default\")?")
            }
            ExprKind::GetAttr { obj, name } if name == "__name__" && t == Ty::Str && pyfast_infer::spec::type_call_arg(obj).is_some() => {
                let x = pyfast_infer::spec::type_call_arg(obj).unwrap();
                let (c, xt) = self.expr(x);
                match xt {
                    t if t == Ty::exc() => format!("rt::Str::from({c}.name())"),
                    t if t.class_id().is_some() => {
                        let n = self.prog.module.class(t.class_id().unwrap()).name.rsplit('.').next().unwrap_or("").to_string();
                        format!("{{ let _ = {c}; rt::Str::from({n:?}) }}")
                    }
                    t => {
                        let n = match t {
                            Ty::None => "NoneType",
                            t => match t.as_opt() {
                                Some(_) => "",
                                None => t.py_name().split('[').next().unwrap_or("object"),
                            },
                        };
                        if n.is_empty() {
                            let inner = t.as_opt().unwrap().py_name().split('[').next().unwrap_or("object").to_string();
                            format!("match {c} {{ Some(_) => rt::Str::from({inner:?}), None => rt::Str::from(\"NoneType\") }}")
                        } else {
                            format!("{{ let _ = {c}; rt::Str::from({n:?}) }}")
                        }
                    }
                }
            }
            ExprKind::GetAttr { obj, name } if is_class(self.ty(obj)) || matches!(self.ty(obj).as_comp(), Some(Comp::Type(..))) => self.attr(obj, name, t),
            ExprKind::BinOp { op, left, right } if is_class(self.ty(left)) || is_class(self.ty(right)) => {
                let n = pyfast_infer::spec::dunder_name(*op);
                let l = self.expr(left);
                let r = self.expr(right);
                match self.dunder(l.clone(), &format!("__{n}__"), vec![r.clone()]) {
                    Some(c) => c,
                    None => self.dunder(r, &format!("__r{n}__"), vec![l]).expect("dunder checked by inference"),
                }
            }
            ExprKind::Unary { op, operand } if *op != UnaryOp::Not && is_class(self.ty(operand)) => {
                let n = match op {
                    UnaryOp::Neg => "__neg__",
                    UnaryOp::Pos => "__pos__",
                    _ => "__invert__",
                };
                let v = self.expr(operand);
                self.dunder(v, n, vec![]).unwrap()
            }
            ExprKind::Subscript { obj, index } if is_class(self.ty(obj)) => {
                let o = self.expr(obj);
                let i = self.expr(index);
                self.dunder(o, "__getitem__", vec![i]).unwrap()
            }
            ExprKind::Call { callee: Callee::Builtin(b @ (Builtin::Len | Builtin::Abs | Builtin::Int | Builtin::Float)), args, .. } if args.len() == 1 && is_class(self.ty(&args[0])) => {
                let n = match b {
                    Builtin::Len => "__len__",
                    Builtin::Abs => "__abs__",
                    Builtin::Int => "__int__",
                    _ => "__float__",
                };
                let v = self.expr(&args[0]);
                self.dunder(v, n, vec![]).unwrap()
            }
            ExprKind::Int(v) => {
                if *v == i64::MIN {
                    "i64::MIN".into()
                } else if *v < 0 {
                    format!("({v}_i64)")
                } else {
                    format!("{v}_i64")
                }
            }
            ExprKind::Float(v) => float_lit(*v),
            ExprKind::Str(s) => format!("rt::Str::from({s:?})"),
            ExprKind::Global { unit, name } => format!("rt::gget(&{}, {name:?})?", gname(*unit, name)),
            ExprKind::Bool(b) => b.to_string(),
            ExprKind::NoneLit => "()".into(),
            ExprKind::Yield(v) => {
                let item = ret_ty(self.spec);
                let (c, vt) = match v {
                    Some(v) => self.expr(v),
                    None => ("()".into(), Ty::None),
                };
                if item.is_never() {
                    // Never reached (`if False: yield x`): nothing is ever yielded.
                    format!("{{ let _ = {c}; }}")
                } else {
                    format!("rt::gen::yield_::<{}>({})", item.rust(), coerce(c, vt, item))
                }
            }
            ExprKind::Await(v) => {
                let (c, vt) = self.expr(v);
                if vt.as_coro().is_some() {
                    format!("{}.run()?", borrow(&c))
                } else {
                    format!("rt::aio::await_obj({c})?")
                }
            }
            ExprKind::Local(n) if self.is_cell(n) => format!("rt::cget(&{}, {n:?})?", rid(n)),
            ExprKind::Local(n) => {
                let copy = !t.is_clone();
                if self.spec.maybe_unbound.contains(n) {
                    let err = if self.func.is_module { "unbound_global" } else { "unbound_local" };
                    let r = rid(n);
                    let base = if copy { r } else { format!("{r}.clone()") };
                    format!("{base}.ok_or_else(|| rt::{err}({n:?}))?")
                } else if copy {
                    rid(n)
                } else {
                    format!("{}.clone()", rid(n))
                }
            }
            ExprKind::BinOp { op, left, right } => {
                let (l, lt) = self.expr(left);
                let (r, rt) = self.expr(right);
                let msg = format!("unsupported operand type(s) for {}: '{}' and '{}'", op.symbol(), tname(lt), tname(rt));
                let msg_l = format!("unsupported operand type(s) for {}: 'NoneType' and '{}'", op.symbol(), tname(rt));
                let msg_r = format!("unsupported operand type(s) for {}: '{}' and 'NoneType'", op.symbol(), tname(lt));
                let _ = msg;
                let (l, lt) = if t == Ty::Obj { (l, lt) } else { unopt(l, lt, &msg_l) };
                let (r, rt) = if t == Ty::Obj { (r, rt) } else { unopt(r, rt, &msg_r) };
                if t == Ty::Obj {
                    format!("rt::py::binop({:?}, {}, {})?", py_op(*op), boxed(&l, lt), boxed(&r, rt))
                } else if t.as_comp().is_some_and(|c| !matches!(c, Comp::Opt(_))) {
                    self.coll_binop(*op, &l, lt, &r, rt, t)
                } else {
                    self.binop(*op, &l, lt, &r, rt, t)
                }
            }
            ExprKind::Unary { op, operand } => {
                let (c, ot) = self.expr(operand);
                let sym = match op {
                    UnaryOp::Neg => "-",
                    UnaryOp::Pos => "+",
                    _ => "~",
                };
                let (c, ot) = if *op == UnaryOp::Not { (c, ot) } else { unopt(c, ot, &format!("bad operand type for unary {sym}: 'NoneType'")) };
                match (op, ot) {
                    (UnaryOp::Not, _) => format!("(!{})", truthy(&c, ot)),
                    (UnaryOp::Neg, Ty::Obj) => format!("rt::py::unary(\"neg\", {c})?"),
                    (UnaryOp::Pos, Ty::Obj) => format!("rt::py::unary(\"pos\", {c})?"),
                    (UnaryOp::Invert, Ty::Obj) => format!("rt::py::unary(\"invert\", {c})?"),
                    (UnaryOp::Neg, Ty::Int) => format!("rt::int::neg({c})?"),
                    (UnaryOp::Neg, Ty::Bool) => format!("(-({c} as i64))"),
                    (UnaryOp::Neg, _) => format!("(-{c})"),
                    (UnaryOp::Pos, _) => as_int(&c, ot),
                    (UnaryOp::Invert, _) => format!("(!{})", as_int(&c, ot)),
                }
            }
            ExprKind::Compare { first, rest } => {
                if rest.len() == 1 {
                    let (l, lt) = self.expr(first);
                    let (r, rt) = self.expr(&rest[0].1);
                    if t == Ty::Obj {
                        format!("rt::py::compare({:?}, {}, {})?", rest[0].0.rt_fn(), boxed(&l, lt), boxed(&r, rt))
                    } else {
                        self.compare_any(rest[0].0, &l, lt, &r, rt)
                    }
                } else {
                    // a < b < c: evaluate each operand at most once, short-circuit.
                    let (l, lt) = self.expr(first);
                    let mut prev = self.fresh();
                    let mut prev_t = lt;
                    let mut code = format!("{{ let {prev} = {l}; ");
                    let mut closers = String::new();
                    for (i, (op, c)) in rest.iter().enumerate() {
                        let (r, rt) = self.expr(c);
                        let cur = self.fresh();
                        let pc = if prev_t.is_clone() { format!("{prev}.clone()") } else { prev.clone() };
                        let cc = if rt.is_clone() { format!("{cur}.clone()") } else { cur.clone() };
                        let cmp = self.compare_any(*op, &pc, prev_t, &cc, rt);
                        if i + 1 == rest.len() {
                            write!(code, "let {cur} = {r}; {cmp}").unwrap();
                        } else {
                            write!(code, "let {cur} = {r}; {cmp} && {{ ").unwrap();
                            closers.push_str(" }");
                        }
                        prev = cur;
                        prev_t = rt;
                    }
                    format!("{code}{closers} }}")
                }
            }
            ExprKind::BoolOp { op, values } => {
                let values = match self.prog.short_circuit(self.spec, *op, values) {
                    Some(n) => &values[..n],
                    None => &values[..],
                };
                if values.len() == 1 {
                    let (c, vt) = self.expr(&values[0]);
                    return (coerce(c, vt, t), t);
                }
                if t == Ty::Bool {
                    let sep = if *op == BoolOpKind::And { " && " } else { " || " };
                    let parts: Vec<String> = values.iter().map(|v| self.expr(v).0).collect();
                    format!("({})", parts.join(sep))
                } else {
                    // Python returns the deciding operand itself.
                    let (lc, lt) = self.expr(values.last().unwrap());
                    let mut acc = coerce(lc, lt, t);
                    for v in values[..values.len() - 1].iter().rev() {
                        let (c, vt) = self.expr(v);
                        let tmp = self.fresh();
                        let test = truthy(&if vt.is_clone() { format!("{tmp}.clone()") } else { tmp.clone() }, vt);
                        let keep = coerce(tmp.clone(), vt, t);
                        acc = match op {
                            BoolOpKind::And => format!("{{ let {tmp} = {c}; if {test} {{ {acc} }} else {{ {keep} }} }}"),
                            BoolOpKind::Or => format!("{{ let {tmp} = {c}; if {test} {{ {keep} }} else {{ {acc} }} }}"),
                        };
                    }
                    acc
                }
            }
            ExprKind::IfExp { test, body, orelse } => {
                match self.prog.static_truth(self.spec, test) {
                    Some(true) => return self.expr(body),
                    Some(false) => return self.expr(orelse),
                    None => {}
                }
                let (c, ct) = self.expr(test);
                let (a, at) = self.expr(body);
                let (b, bt) = self.expr(orelse);
                format!("(if {} {{ {} }} else {{ {} }})", truthy(&c, ct), coerce(a, at, t), coerce(b, bt, t))
            }
            ExprKind::Call { callee: Callee::Builtin(b @ (Builtin::Print | Builtin::PrintKw)), args, .. } if args.iter().any(|a| matches!(a.kind, ExprKind::Starred(_))) => {
                // print(*items): strings collected at run time.
                let n_items = if *b == Builtin::PrintKw { args.len() - 3 } else { args.len() };
                let mut code = String::from("{ let mut __p: Vec<rt::Str> = Vec::new(); ");
                for a in &args[..n_items] {
                    match &a.kind {
                        ExprKind::Starred(inner) => {
                            let (c, t) = self.expr(inner);
                            let el = pyfast_infer::native::iter_elem(t).unwrap_or(Ty::Obj);
                            write!(code, "for __e in {} {{ __p.push({}); }} ", coll::iter_vec(&c, t), to_str("__e", el)).unwrap();
                        }
                        _ => {
                            let (c, t) = self.expr(a);
                            write!(code, "__p.push({}); ", to_str(&c, t)).unwrap();
                        }
                    }
                }
                if *b == Builtin::PrintKw {
                    let n = args.len();
                    let (s, st) = self.expr(&args[n - 3]);
                    let (en, et) = self.expr(&args[n - 2]);
                    let (fl, ft) = self.expr(&args[n - 1]);
                    write!(code, "rt::io::print_kw(&__p, &{}, &{}, {}) }}", to_str(&s, st), to_str(&en, et), truthy(&fl, ft)).unwrap();
                } else {
                    code.push_str("rt::print(&__p) }");
                }
                code
            }
            ExprKind::Call { callee, args, order } => {
                let vals: Vec<(String, Ty)> = args.iter().map(|a| self.expr(a)).collect();
                match callee {
                    Callee::Func(fid) => {
                        let key = self.prog.resolve_key(SpecKey { func: *fid, args: vals.iter().map(|v| v.1).collect() });
                        let callee = self.prog.spec(&key).expect("missing specialization");
                        // The shared object-typed specialization takes boxed arguments.
                        let mut a: Vec<String> = vals.into_iter().zip(&key.args).map(|(v, kt)| coerce(v.0, v.1, *kt)).collect();
                        if order.is_empty() {
                            format!("{}({})?", callee.mangled, a.join(", "))
                        } else {
                            // Keyword arguments out of parameter order: evaluate in source order.
                            let mut lets = String::new();
                            for &i in order {
                                let tmp = self.fresh();
                                write!(lets, "let {tmp} = {}; ", a[i]).unwrap();
                                a[i] = tmp;
                            }
                            format!("{{ {lets}{}({})? }}", callee.mangled, a.join(", "))
                        }
                    }
                    Callee::Builtin(b) => self.builtin(*b, vals, t),
                }
            }
            ExprKind::Annotated { ty, value } => {
                let (c, vt) = self.expr(value);
                let c = if vt == Ty::Obj && t != Ty::Obj {
                    match t {
                        Ty::Int => format!("rt::py::unbox_annotated::<i64>(&{}, \"int\")?", borrow(&c)),
                        Ty::Str => format!("rt::py::unbox_annotated::<rt::Str>(&{}, \"str\")?", borrow(&c)),
                        _ => format!("rt::py::unbox_annotated::<bool>(&{}, \"bool\")?", borrow(&c)),
                    }
                } else {
                    c
                };
                let _ = ty;
                c
            }
            ExprKind::ExternCall { ext, func, args } => self.extern_call(*ext, *func, None, args),
            ExprKind::GetAttr { obj, name } if self.ty(obj).as_ext_struct().is_some() => self.ext_field(obj, name),
            ExprKind::NewExc { kind, args } => match args.first() {
                None => format!("rt::Exc::new({kind:?}, \"\")"),
                Some(a) => {
                    let (c, at) = self.expr(a);
                    if kind == "KeyError" {
                        let v = if at == Ty::Obj { c } else { format!("&{}", borrow(&c)) };
                        let v = if at == Ty::Obj { format!("&{}", borrow(&v)) } else { v };
                        format!("rt::Exc::new(\"KeyError\", rt::conv::repr_of({v}).to_string())")
                    } else {
                        format!("rt::Exc::new({kind:?}, {}.to_string())", to_str(&c, at))
                    }
                }
            },
            ExprKind::Slot(i) => format!("SLOT_{i}_{}.get()?", ident(&self.prog.module.slots[*i].binding)),
            ExprKind::PyBuiltin(n) => format!("rt::py::builtin({n:?})?"),
            ExprKind::GetAttr { obj, name } => {
                let o = self.obj(obj);
                format!("rt::py::getattr(&{}, {name:?})?", borrow(&o))
            }
            ExprKind::CallObj { func, args, kwargs } if !matches!(self.prog.classify_call(self.spec, func, args, kwargs), CallClass::Bridge | CallClass::Pending) => {
                match self.prog.classify_call(self.spec, func, args, kwargs) {
                    CallClass::UserMethod { func: fid, kind } => {
                        let ExprKind::GetAttr { obj, .. } = &func.kind else { unreachable!() };
                        self.method_call(e, obj, fid, kind, args, kwargs)
                    }
                    CallClass::ClosureCall => self.closure_call(e, func, args, kwargs),
                    CallClass::ExtMethod { ext, func: fi } => {
                        let ExprKind::GetAttr { obj, .. } = &func.kind else { unreachable!() };
                        let recv = self.expr(obj);
                        self.extern_call(ext, fi, Some(recv), args)
                    }
                    CallClass::Builtin(name) if matches!(name.as_str(), "map" | "filter") || (matches!(name.as_str(), "sorted" | "min" | "max") && kwargs.iter().any(|(k, _)| k == "key")) => {
                        self.higher_order(&name, args, kwargs, t)
                    }
                    CallClass::UnionMethod(name) => {
                        let ExprKind::GetAttr { obj, .. } = &func.kind else { unreachable!() };
                        self.union_method(e, obj, &name, args, kwargs, t)
                    }
                    CallClass::RuntimeIsinstance(cs) => {
                        let (c, ct) = self.expr(&args[0]);
                        let ur = ct.rust();
                        let hits: Vec<String> = ct
                            .union_members()
                            .unwrap()
                            .iter()
                            .filter(|m| cs.iter().any(|k| self.prog.module.is_subclass(m.class_id().unwrap(), *k)))
                            .map(|m| format!("{ur}::{}(_)", m.variant_name()))
                            .collect();
                        format!("matches!({c}, {})", hits.join(" | "))
                    }
                    CallClass::Construct(c) => {
                        let f = self.expr(func).0;
                        format!("{{ let _ = {f}; {} }}", self.new_instance(e, c, args, kwargs))
                    }
                    CallClass::StaticBool(b) => {
                        let parts: Vec<String> = args.iter().take(1).map(|a| self.expr(a).0).collect();
                        format!("{{ let _ = {}; {b} }}", parts.join(", "))
                    }
                    CallClass::Method { recv, name } => {
                        let ExprKind::GetAttr { obj, .. } = &func.kind else { unreachable!() };
                        self.method(obj, recv, &name, args, kwargs, t)
                    }
                    CallClass::Builtin(name) => self.native_builtin(&name, args, kwargs, t),
                    CallClass::Bridge | CallClass::Pending => unreachable!(),
                }
            }
            ExprKind::CallObj { func, args, kwargs } if args.iter().any(|a| matches!(a.kind, ExprKind::Starred(_))) || kwargs.iter().any(|(k, _)| k == "**") => {
                let f = self.obj(func);
                let mut code = String::from("{ let mut __a: Vec<rt::py::Obj> = Vec::new(); let mut __k: Vec<(String, rt::py::Obj)> = Vec::new(); ");
                for a in args {
                    match &a.kind {
                        ExprKind::Starred(inner) => {
                            let o = self.obj(inner);
                            write!(code, "__a.extend(rt::py::to_vec(&{})?); ", borrow(&o)).unwrap();
                        }
                        _ => {
                            let o = self.obj(a);
                            write!(code, "__a.push({o}); ").unwrap();
                        }
                    }
                }
                for (k, v) in kwargs {
                    let o = self.obj(v);
                    if k == "**" {
                        write!(code, "__k.extend(rt::py::kw_items(&{})?); ", borrow(&o)).unwrap();
                    } else {
                        write!(code, "__k.push(({k:?}.to_string(), {o})); ").unwrap();
                    }
                }
                write!(code, "rt::py::call_dyn(&{}, __a, __k)? }}", borrow(&f)).unwrap();
                code
            }
            ExprKind::CallObj { func, args, kwargs } => {
                let f = self.obj(func);
                let a: Vec<String> = args.iter().map(|x| self.obj(x)).collect();
                let k: Vec<String> = kwargs.iter().map(|(n, x)| format!("({n:?}, {})", self.obj(x))).collect();
                format!("rt::py::call(&{}, vec![{}], vec![{}])?", borrow(&f), a.join(", "), k.join(", "))
            }
            ExprKind::List(_) | ExprKind::Tuple(_) | ExprKind::Dict(_) | ExprKind::Set(_) => self.literal(e, t),
            ExprKind::Unpack { value, n, star } => self.unpack(value, *n, *star, t),
            ExprKind::Starred(inner) => self.expr(inner).0,
            ExprKind::Comp { kind, elt, val, gens } => self.comp(*kind, elt, val.as_deref(), gens, t),
            ExprKind::Slice { lo, hi, step } => {
                let part = |me: &mut Self, x: &Option<Box<Expr>>| match x {
                    None => "rt::py::none()".to_string(),
                    Some(x) => me.obj(x),
                };
                let (a, b, c) = (part(self, lo), part(self, hi), part(self, step));
                format!("rt::py::slice({a}, {b}, {c})?")
            }
            ExprKind::Subscript { obj, index } if self.ty(obj) != Ty::Obj => self.subscript(obj, index, t),
            ExprKind::Subscript { obj, index } => {
                let o = self.obj(obj);
                let i = self.obj(index);
                format!("rt::py::getitem(&{}, {i})?", borrow(&o))
            }
        };
        (code, t)
    }

    fn binop(&mut self, op: BinOp, l: &str, lt: Ty, r: &str, rt: Ty, t: Ty) -> String {
        use BinOp::*;
        if op == Mod && lt == Ty::Str && t == Ty::Str {
            // printf-style formatting: a tuple supplies the arguments, anything else is one.
            let args = match rt.tuple_items() {
                Some(ts) => {
                    let parts: Vec<String> = ts.iter().enumerate().map(|(i, x)| coll::to_arg(&format!("__a.{i}"), *x)).collect();
                    return format!("{{ let __a = {r}; rt::fmt::percent(&{}, &[{}])? }}", borrow(l), parts.join(", "));
                }
                None => match rt.as_comp() {
                    Some(Comp::TupleVar(e)) => {
                        return format!("rt::fmt::percent(&{}, &{}.to_vec().into_iter().map(|__x| {}).collect::<Vec<_>>())?", borrow(l), r, coll::to_arg("__x", e));
                    }
                    _ => coll::to_arg(r, rt),
                },
            };
            return format!("rt::fmt::percent(&{}, &[{args}])?", borrow(l));
        }
        match t {
            Ty::Str => match (lt, rt) {
                (Ty::Str, Ty::Str) => format!("rt::string::concat(&{}, &{})", borrow(l), borrow(r)),
                (Ty::Str, n) => format!("rt::string::repeat(&{}, {})?", borrow(l), as_int(r, n)),
                (n, _) => format!("rt::string::repeat(&{}, {})?", borrow(r), as_int(l, n)),
            },
            Ty::Bool => format!("({l} {} {r})", op.symbol()),
            Ty::Float => {
                if op == Div && lt != Ty::Float && rt != Ty::Float {
                    return format!("rt::int::truediv({}, {})?", as_int(l, lt), as_int(r, rt));
                }
                let (a, b) = (as_float(l, lt), as_float(r, rt));
                match op {
                    Add | Sub | Mul => format!("({a} {} {b})", op.symbol()),
                    _ => format!("rt::float::{}({a}, {b})?", op.rt_fn()),
                }
            }
            Ty::Int => {
                let (a, b) = (as_int(l, lt), as_int(r, rt));
                match op {
                    BitAnd | BitOr | BitXor => format!("({a} {} {b})", op.symbol()),
                    _ => format!("rt::int::{}({a}, {b})?", op.rt_fn()),
                }
            }
            Ty::None | Ty::Obj => unreachable!(),
            Ty::C(_) => format!("rt::ops::{}(&{}, &{})?", op.rt_fn(), borrow(l), borrow(r)),
        }
    }

    /// One comparison, including native collections.
    fn compare_any(&mut self, op: CmpOp, l: &str, lt: Ty, r: &str, rt: Ty) -> String {
        if pyfast_infer::spec::class_like(lt) || pyfast_infer::spec::class_like(rt) {
            return self.compare_class(op, l, lt, r, rt);
        }
        let comp = |t: Ty| t.as_comp().is_some_and(|c| !matches!(c, Comp::Opt(_) | Comp::Exc));
        if lt == Ty::Obj || rt == Ty::Obj || !(comp(lt) || comp(rt)) {
            return compare(op, l, lt, r, rt);
        }
        match op {
            CmpOp::In | CmpOp::NotIn => {
                let c = self.contains(l, lt, r, rt);
                if op == CmpOp::NotIn { format!("!{c}") } else { c }
            }
            CmpOp::Is | CmpOp::IsNot => {
                let neg = if op == CmpOp::IsNot { "!" } else { "" };
                if lt == rt && lt.is_mutable() {
                    format!("{neg}{l}.is(&{})", borrow(r))
                } else {
                    format!("{{ let _ = {l}; let _ = {r}; {} }}", op == CmpOp::IsNot)
                }
            }
            _ => {
                let j = pyfast_infer::native::ty_join(lt, rt, false);
                match j {
                    None => {
                        let v = matches!(op, CmpOp::NotEq);
                        format!("{{ let _ = {l}; let _ = {r}; {v} }}")
                    }
                    Some(j) => {
                        let (a, b) = (coll::convert(l, lt, j), coll::convert(r, rt, j));
                        match op {
                            CmpOp::Eq => format!("rt::coll::eq(&{}, &{})", borrow(&a), borrow(&b)),
                            CmpOp::NotEq => format!("rt::coll::ne(&{}, &{})", borrow(&a), borrow(&b)),
                            o if j.set_elem().is_some() => {
                                // Set inclusion: <= is issubset, < proper subset.
                                match o {
                                    CmpOp::LtE => format!("{a}.issubset(&{b})"),
                                    CmpOp::GtE => format!("{a}.issuperset(&{b})"),
                                    CmpOp::Lt => format!("{{ let (__a, __b) = ({a}, {b}); __a.issubset(&__b) && __a.len() < __b.len() }}"),
                                    _ => format!("{{ let (__a, __b) = ({a}, {b}); __a.issuperset(&__b) && __a.len() > __b.len() }}"),
                                }
                            }
                            o => format!("rt::coll::{}(&{}, &{})?", o.rt_fn(), borrow(&a), borrow(&b)),
                        }
                    }
                }
            }
        }
    }

    /// Comparison with a native instance operand (dunders, else identity).
    fn compare_class(&mut self, op: CmpOp, l: &str, lt: Ty, r: &str, rt: Ty) -> String {
        let (lv, rv) = ((l.to_string(), lt), (r.to_string(), rt));
        let truthy_of = |code: String, me: &Self, name: &str, recv: Ty, other: Ty| -> String {
            let c = recv.class_id().unwrap();
            let m = me.prog.module.find_method(c, name).unwrap();
            let rty = me.prog.spec(&SpecKey { func: m.func, args: vec![recv, other] }).and_then(|s| match s.ret {
                Slot::Known(t) => Some(t),
                _ => None,
            });
            truthy(&code, rty.unwrap_or(Ty::Bool))
        };
        match op {
            CmpOp::In | CmpOp::NotIn => {
                let c = self.dunder(rv.clone(), "__contains__", vec![lv.clone()]).map(|code| truthy_of(code, self, "__contains__", rt, lt));
                let c = c.unwrap_or_else(|| self.contains(l, lt, r, rt));
                if op == CmpOp::NotIn { format!("!{c}") } else { c }
            }
            CmpOp::Is | CmpOp::IsNot => {
                let neg = if op == CmpOp::IsNot { "!" } else { "" };
                if lt == rt { format!("{neg}{l}.is(&{})", borrow(r)) } else { format!("{{ let _ = {l}; let _ = {r}; {} }}", op == CmpOp::IsNot) }
            }
            _ => {
                let (fwd, refl) = pyfast_infer::spec::cmp_dunder(op).unwrap();
                if let Some(code) = self.dunder(lv.clone(), fwd, vec![rv.clone()]) {
                    return truthy_of(code, self, fwd, lt, rt);
                }
                if let Some(code) = self.dunder(rv.clone(), refl, vec![lv.clone()]) {
                    return truthy_of(code, self, refl, rt, lt);
                }
                if op == CmpOp::NotEq {
                    if let Some(code) = self.dunder(lv.clone(), "__eq__", vec![rv.clone()]) {
                        return format!("!{}", truthy_of(code, self, "__eq__", lt, rt));
                    }
                }
                // Default: identity (field-wise for dataclasses, via PyEq).
                let same = if lt == rt { format!("rt::coll::eq(&{}, &{})", borrow(l), borrow(r)) } else { format!("{{ let _ = {l}; let _ = {r}; false }}") };
                if op == CmpOp::NotEq { format!("!{same}") } else { same }
            }
        }
    }

    fn py_builtin_call(&mut self, name: &str, vals: Vec<(String, Ty)>) -> String {
        let a: Vec<String> = vals.iter().map(|(c, t)| boxed(c, *t)).collect();
        format!("rt::py::call(&rt::py::builtin({name:?})?, vec![{}], vec![])?", a.join(", "))
    }

    fn builtin(&mut self, b: Builtin, vals: Vec<(String, Ty)>, t: Ty) -> String {
        let msg = match b {
            Builtin::Int => "int() argument must be a string, a bytes-like object or a real number, not 'NoneType'".to_string(),
            Builtin::Float => "float() argument must be a string or a real number, not 'NoneType'".to_string(),
            Builtin::Abs => "bad operand type for abs(): 'NoneType'".to_string(),
            Builtin::Len => "object of type 'NoneType' has no len()".to_string(),
            _ => "'<' not supported between instances of 'NoneType' and 'int'".to_string(),
        };
        let vals: Vec<(String, Ty)> = if matches!(b, Builtin::Print | Builtin::PrintKw | Builtin::Str | Builtin::Bool) || t == Ty::Obj {
            vals
        } else {
            vals.into_iter().map(|(c, vt)| unopt(c, vt, &msg)).collect()
        };
        let one = || vals[0].clone();
        match b {
            Builtin::Print if vals.iter().any(|(_, t)| t.has_mutable()) && vals.len() > 1 => {
                // print() calls str() only after evaluating every argument.
                let lets: String = vals.iter().enumerate().map(|(i, (c, _))| format!("let __p{i} = {c}; ")).collect();
                let parts: Vec<String> = vals.iter().enumerate().map(|(i, (_, t))| to_str(&format!("__p{i}"), *t)).collect();
                format!("{{ {lets}rt::print(&[{}]) }}", parts.join(", "))
            }
            Builtin::Print => {
                let parts: Vec<String> = vals.iter().map(|(c, t)| to_str(c, *t)).collect();
                format!("rt::print(&[{}])", parts.join(", "))
            }
            Builtin::PrintKw => {
                let n = vals.len();
                let parts: Vec<String> = vals[..n - 3].iter().map(|(c, t)| to_str(c, *t)).collect();
                let (sep, end) = (to_str(&vals[n - 3].0, vals[n - 3].1), to_str(&vals[n - 2].0, vals[n - 2].1));
                let flush = truthy(&vals[n - 1].0, vals[n - 1].1);
                format!("rt::io::print_kw(&[{}], &{}, &{}, {})", parts.join(", "), sep, end, flush)
            }
            Builtin::Str => match vals.first() {
                None => "rt::Str::from(\"\")".into(),
                Some((c, t)) => to_str(c, *t),
            },
            Builtin::Bool => match vals.first() {
                None => "false".into(),
                Some((c, t)) => truthy(c, *t),
            },
            Builtin::Abs => {
                let (c, at) = one();
                match at {
                    Ty::Int => format!("rt::int::abs({c})?"),
                    Ty::Bool => format!("({c} as i64)"),
                    Ty::Obj => format!("rt::py::unary(\"abs\", {c})?"),
                    _ => format!("{c}.abs()"),
                }
            }
            Builtin::Int => match vals.first() {
                None => "0_i64".into(),
                Some((c, at)) => match at {
                    Ty::Int => c.clone(),
                    Ty::Bool => format!("({c} as i64)"),
                    Ty::Float => format!("rt::conv::int_from_float({c})?"),
                    Ty::Obj => format!("rt::py::int_of(&{})?", borrow(c)),
                    _ => format!("rt::conv::int_from_str(&{})?", borrow(c)),
                },
            },
            Builtin::Float => match vals.first() {
                None => "0.0_f64".into(),
                Some((c, at)) => match at {
                    Ty::Str => format!("rt::conv::float_from_str(&{})?", borrow(c)),
                    Ty::Obj => format!("rt::py::float_of(&{})?", borrow(c)),
                    at => as_float(c, *at),
                },
            },
            Builtin::Len => match vals[0].1 {
                Ty::Obj => format!("rt::py::len(&{})?", borrow(&vals[0].0)),
                Ty::Str => format!("rt::string::len(&{})", borrow(&vals[0].0)),
                lt => match lt.tuple_items() {
                    Some(ts) => format!("{{ let _ = {}; {}_i64 }}", vals[0].0, ts.len()),
                    None => format!("{}.len()", borrow(&vals[0].0)),
                },
            },
            Builtin::Min | Builtin::Max if vals.len() == 1 && t != Ty::Obj => {
                format!("rt::coll::min_of({}, {})?", coll::iter_vec(&vals[0].0, vals[0].1), b == Builtin::Max)
            }
            Builtin::Min | Builtin::Max if t == Ty::Obj => self.py_builtin_call(b.name(), vals),
            Builtin::Min | Builtin::Max => {
                // Python keeps the first extreme element: replace only on strict improvement.
                let cmp = if b == Builtin::Min { "<" } else { ">" };
                let m = self.fresh();
                let mut code = format!("{{ let mut {m} = {}; ", vals[0].0);
                for (c, _) in &vals[1..] {
                    let v = self.fresh();
                    write!(code, "let {v} = {c}; if {v} {cmp} {m} {{ {m} = {v}; }} ").unwrap();
                }
                write!(code, "{m} }}").unwrap();
                code
            }
        }
    }
}

/// Comparisons with a `T | None` operand.
fn compare_opt(op: CmpOp, l: &str, lt: Ty, r: &str, rt: Ty) -> String {
    let none_test = |code: &str, neg: bool| format!("{}{}.is_none()", if neg { "!" } else { "" }, code);
    let neg = matches!(op, CmpOp::IsNot | CmpOp::NotEq);
    match op {
        CmpOp::Is | CmpOp::IsNot | CmpOp::Eq | CmpOp::NotEq if rt == Ty::None => format!("{{ let _ = {r}; {} }}", none_test(l, neg)),
        CmpOp::Is | CmpOp::IsNot | CmpOp::Eq | CmpOp::NotEq if lt == Ty::None => format!("{{ let _ = {l}; {} }}", none_test(r, neg)),
        CmpOp::Is | CmpOp::IsNot => format!("{{ let _ = {l}; let _ = {r}; {} }}", neg),
        CmpOp::Eq | CmpOp::NotEq => {
            // None equals only None; otherwise compare the payloads.
            let (lb, rb) = (lt.as_opt().unwrap_or(lt), rt.as_opt().unwrap_or(rt));
            let lv = if lt.as_opt().is_some() { format!("Some(__a)") } else { "__a".into() };
            let rv = if rt.as_opt().is_some() { format!("Some(__b)") } else { "__b".into() };
            let inner = compare(op, "__a", lb, "__b", rb);
            let both_none = if lt.as_opt().is_some() && rt.as_opt().is_some() { format!("(None, None) => {}, ", !neg) } else { String::new() };
            format!("(match ({l}, {r}) {{ ({lv}, {rv}) => {inner}, {both_none}_ => {neg} }})")
        }
        _ => {
            let msg = format!("'{}' not supported between instances of '{}' and '{}'", cmp_sym(op), tname(lt), tname(rt));
            let (a, at) = unopt(l.to_string(), lt, &msg);
            let (b, bt) = unopt(r.to_string(), rt, &msg);
            compare(op, &a, at, &b, bt)
        }
    }
}

fn mirror(op: CmpOp) -> CmpOp {
    match op {
        CmpOp::Lt => CmpOp::Gt,
        CmpOp::LtE => CmpOp::GtE,
        CmpOp::Gt => CmpOp::Lt,
        CmpOp::GtE => CmpOp::LtE,
        o => o,
    }
}

fn cmp_sym(op: CmpOp) -> &'static str {
    match op {
        CmpOp::Eq => "==",
        CmpOp::NotEq => "!=",
        CmpOp::Lt => "<",
        CmpOp::LtE => "<=",
        CmpOp::Gt => ">",
        CmpOp::GtE => ">=",
        _ => unreachable!(),
    }
}

/// Boolean result of one comparison.
fn compare(op: CmpOp, l: &str, lt: Ty, r: &str, rt: Ty) -> String {
    let int_like = |t: Ty| matches!(t, Ty::Int | Ty::Bool);
    let any_obj = lt == Ty::Obj || rt == Ty::Obj;
    if !any_obj && (lt.as_opt().is_some() || rt.as_opt().is_some()) {
        return compare_opt(op, l, lt, r, rt);
    }
    match op {
        CmpOp::In | CmpOp::NotIn => {
            let neg = if op == CmpOp::NotIn { "!" } else { "" };
            if any_obj {
                format!("{neg}rt::py::contains({}, {})?", boxed(l, lt), boxed(r, rt))
            } else {
                format!("{neg}rt::string::contains(&{}, &{})", borrow(l), borrow(r))
            }
        }
        CmpOp::Is | CmpOp::IsNot => {
            let neg = if op == CmpOp::IsNot { "!" } else { "" };
            if any_obj {
                format!("{neg}rt::py::is(&{}, &{})", boxed(l, lt), boxed(r, rt))
            } else {
                // Native values: only `x is None` reaches here.
                let same = lt == Ty::None && rt == Ty::None;
                let v = if op == CmpOp::Is { same } else { !same };
                format!("{{ let _ = {l}; let _ = {r}; {v} }}")
            }
        }
        _ if any_obj => format!("rt::py::compare_bool({:?}, {}, {})?", op.rt_fn(), boxed(l, lt), boxed(r, rt)),
        _ => match (lt, rt) {
            (a, b) if a == b => format!("({l} {} {r})", cmp_sym(op)),
            (a, b) if int_like(a) && int_like(b) => format!("({} {} {})", as_int(l, a), cmp_sym(op), as_int(r, b)),
            (a, Ty::Float) if int_like(a) => format!("rt::int::{}_f({}, {r})", op.rt_fn(), as_int(l, a)),
            (Ty::Float, b) if int_like(b) => format!("rt::int::{}_f({}, {l})", mirror(op).rt_fn(), as_int(r, b)),
            // Different, non-numeric types: equality is False, inequality True.
            _ => {
                let v = matches!(op, CmpOp::NotEq);
                format!("{{ let _ = {l}; let _ = {r}; {v} }}")
            }
        },
    }
}
